-- =====================================================================
-- 无人货柜补货/盘点/临期下架服务 初始化 schema
-- 数据库: PostgreSQL; 测试环境使用 H2(PostgreSQL 兼容模式), 故避免使用
-- PG 专有类型(enum/jsonb), 全部使用 varchar + check 约束
-- =====================================================================

-- 供应商
CREATE TABLE supplier (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(128) NOT NULL,
    contact             VARCHAR(128),
    settlement_account  VARCHAR(128),
    created_at          TIMESTAMP    NOT NULL
);

-- 员工账号(补货员/运营/财务/客服/管理员/供应商)
CREATE TABLE staff (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(64)  NOT NULL,
    role        VARCHAR(32)  NOT NULL CHECK (role IN ('ROOT','OPERATOR','FINANCE','CUSTOMER_SERVICE','REPLENISHER','SUPPLIER')),
    token       VARCHAR(64)  NOT NULL UNIQUE,
    supplier_id BIGINT REFERENCES supplier(id),
    active      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMP    NOT NULL
);

-- 商品目录
CREATE TABLE product (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku                     VARCHAR(64) NOT NULL UNIQUE,
    name                    VARCHAR(128) NOT NULL,
    category                VARCHAR(64),
    unit_price              NUMERIC(12,2) NOT NULL,
    cost_price              NUMERIC(12,2) NOT NULL,
    temp_requirement        VARCHAR(16) NOT NULL CHECK (temp_requirement IN ('AMBIENT','CHILLED','FROZEN')),
    active                  BOOLEAN NOT NULL DEFAULT TRUE,
    created_at              TIMESTAMP NOT NULL
);

-- 柜机点位
CREATE TABLE cabinet (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(64) NOT NULL UNIQUE,
    name            VARCHAR(128) NOT NULL,
    location_type   VARCHAR(16) NOT NULL CHECK (location_type IN ('COMMUNITY','OFFICE','HOSPITAL')),
    address         VARCHAR(256),
    temp_type       VARCHAR(16) NOT NULL CHECK (temp_type IN ('AMBIENT','CHILLED','FROZEN','MIXED')),
    status          VARCHAR(24) NOT NULL DEFAULT 'NORMAL'
                    CHECK (status IN ('NORMAL','TEMP_ALARM','MAINTENANCE','OFFLINE')),
    active          BOOLEAN NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMP NOT NULL
);

-- 货道
CREATE TABLE channel (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cabinet_id      BIGINT NOT NULL REFERENCES cabinet(id),
    code            VARCHAR(16) NOT NULL,
    expected_sku    VARCHAR(64),
    capacity        INT NOT NULL DEFAULT 10,
    temp_type       VARCHAR(16) NOT NULL CHECK (temp_type IN ('AMBIENT','CHILLED','FROZEN')),
    active          BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_channel_cabinet_code UNIQUE (cabinet_id, code)
);

-- 商品批次(保质期追踪的最小单位)
CREATE TABLE product_batch (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_no            VARCHAR(64) NOT NULL UNIQUE,
    sku                 VARCHAR(64) NOT NULL,
    supplier_id         BIGINT NOT NULL REFERENCES supplier(id),
    production_date     DATE NOT NULL,
    expiry_date         DATE NOT NULL,
    temp_requirement    VARCHAR(16) NOT NULL CHECK (temp_requirement IN ('AMBIENT','CHILLED','FROZEN')),
    inbound_qty         INT NOT NULL,
    unit_cost           NUMERIC(12,2) NOT NULL,
    -- IN_WAREHOUSE 仓内 / ON_SHELF 在柜 / NEAR_EXPIRY 临期 / QUARANTINED 温控隔离
    -- REMOVED 已下架 / SCRAPPED 已报损 / SETTLED 已结算
    status              VARCHAR(24) NOT NULL DEFAULT 'IN_WAREHOUSE',
    created_at          TIMESTAMP NOT NULL
);
CREATE INDEX idx_batch_sku ON product_batch(sku);
CREATE INDEX idx_batch_expiry ON product_batch(expiry_date);

-- 补货任务
CREATE TABLE replenishment (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no        VARCHAR(64) NOT NULL UNIQUE,
    cabinet_id      BIGINT NOT NULL REFERENCES cabinet(id),
    staff_id        BIGINT NOT NULL REFERENCES staff(id),
    arrived_at      TIMESTAMP NOT NULL,
    completed_at    TIMESTAMP,
    -- OPEN 进行中 / CONFIRMED 已确认上架 / HAS_ISSUE 含放错货道等待处理项
    status          VARCHAR(16) NOT NULL DEFAULT 'OPEN'
                    CHECK (status IN ('OPEN','CONFIRMED','HAS_ISSUE')),
    photo_url       VARCHAR(512),
    note            VARCHAR(512),
    created_at      TIMESTAMP NOT NULL
);

-- 补货明细(每行 = 某批次放进某货道)
CREATE TABLE replenishment_item (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    replenishment_id    BIGINT NOT NULL REFERENCES replenishment(id),
    batch_id            BIGINT NOT NULL REFERENCES product_batch(id),
    channel_id          BIGINT NOT NULL REFERENCES channel(id),
    sku                 VARCHAR(64) NOT NULL,
    qty                 INT NOT NULL CHECK (qty > 0),
    expiry_date         DATE NOT NULL,
    -- OK 正常 / WRONG_CHANNEL 放错货道 / MOVED 已纠正移走
    status              VARCHAR(16) NOT NULL DEFAULT 'OK'
                        CHECK (status IN ('OK','WRONG_CHANNEL','MOVED')),
    issue_note          VARCHAR(512),
    created_at          TIMESTAMP NOT NULL
);

-- 批次在货道上的当前库存(补货/售卖/下架/报损都更新此表)
CREATE TABLE batch_inventory (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id            BIGINT NOT NULL REFERENCES product_batch(id),
    channel_id          BIGINT NOT NULL REFERENCES channel(id),
    cabinet_id          BIGINT NOT NULL REFERENCES cabinet(id),
    on_shelf_qty        INT NOT NULL DEFAULT 0,
    quarantined_qty     INT NOT NULL DEFAULT 0,
    near_expiry_qty     INT NOT NULL DEFAULT 0,
    removed_qty         INT NOT NULL DEFAULT 0,
    sold_qty            INT NOT NULL DEFAULT 0,
    scrapped_qty        INT NOT NULL DEFAULT 0,
    updated_at          TIMESTAMP NOT NULL,
    CONSTRAINT uq_batch_channel UNIQUE (batch_id, channel_id)
);
CREATE INDEX idx_inv_cabinet ON batch_inventory(cabinet_id);
CREATE INDEX idx_inv_channel ON batch_inventory(channel_id);

-- 库存流水(可回放的每一次库存变化)
CREATE TABLE inventory_ledger (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id        BIGINT REFERENCES product_batch(id),
    channel_id      BIGINT NOT NULL,
    cabinet_id      BIGINT NOT NULL,
    sku             VARCHAR(64) NOT NULL,
    change_qty      INT NOT NULL,
    balance_qty     INT NOT NULL,
    reason_code     VARCHAR(32) NOT NULL CHECK (reason_code IN (
                        'REPLENISH','SALE','SALE_REVERSED','RETURN_TO_SHELF',
                        'JAM_RECOVER','WRONG_CHANNEL_MOVE','NEAR_EXPIRY_MARK',
                        'REMOVE_EXPIRY','TEMP_QUARANTINE','TEMP_RELEASE',
                        'SCRAP','STOCKTAKE_ADJUST')),
    ref_type        VARCHAR(32),
    ref_id          BIGINT,
    operator_id     BIGINT,
    created_at      TIMESTAMP NOT NULL
);
CREATE INDEX idx_ledger_batch ON inventory_ledger(batch_id);
CREATE INDEX idx_ledger_channel_time ON inventory_ledger(channel_id, created_at);

-- 开门购物会话
CREATE TABLE door_session (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_no      VARCHAR(64) NOT NULL UNIQUE,
    cabinet_id      BIGINT NOT NULL REFERENCES cabinet(id),
    user_id         VARCHAR(64) NOT NULL,
    opened_at       TIMESTAMP NOT NULL,
    closed_at       TIMESTAMP,
    -- OPEN / CLOSED / DISPUTED
    status          VARCHAR(16) NOT NULL DEFAULT 'OPEN',
    -- PENDING 待结算 / SETTLED 已结算 / ADJUSTED 人工调整 / REFUNDED 已退款
    settle_status   VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    amount          NUMERIC(12,2) NOT NULL DEFAULT 0,
    order_id        BIGINT,
    video_clip_url  VARCHAR(512),
    clip_start_ms   BIGINT,
    clip_end_ms     BIGINT,
    uncertainty     BOOLEAN NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMP NOT NULL
);
CREATE INDEX idx_session_cabinet_time ON door_session(cabinet_id, opened_at);
CREATE INDEX idx_session_user ON door_session(user_id);

-- 识别事件(重量/视觉/RFID 三模, 先各自成原始事件, 再对账)
CREATE TABLE recognition_event (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id          BIGINT NOT NULL REFERENCES door_session(id),
    event_no            INT NOT NULL,
    occurred_at         TIMESTAMP NOT NULL,
    modality            VARCHAR(16) NOT NULL CHECK (modality IN ('WEIGHT','VISION','RFID')),
    -- PICK 拿起 / RETURN 放回 / DETECT 其他检测
    action              VARCHAR(16) NOT NULL CHECK (action IN ('PICK','RETURN','DETECT')),
    channel_id          BIGINT REFERENCES channel(id),
    sku                 VARCHAR(64),
    batch_id            BIGINT REFERENCES product_batch(id),
    confidence          NUMERIC(5,4),
    weight_delta_g      INT,
    raw_payload         VARCHAR(2048),
    -- 对账结论: PICK 计售卖 / RETURN 计放回 / UNCERTAIN 证据不足挂起 / IGNORED 噪声
    reconciled_result   VARCHAR(16) CHECK (reconciled_result IN ('PICK','RETURN','UNCERTAIN','IGNORED')),
    reconciled_at       TIMESTAMP,
    CONSTRAINT uq_event_session_no UNIQUE (session_id, event_no)
);
CREATE INDEX idx_event_session ON recognition_event(session_id);

-- 会话证据(开门记录/识别快照/视频片段/重量曲线/补货照片)
CREATE TABLE session_evidence (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id      BIGINT NOT NULL REFERENCES door_session(id),
    evidence_type   VARCHAR(24) NOT NULL CHECK (evidence_type IN (
                        'DOOR_OPEN','DOOR_CLOSE','VIDEO_CLIP','WEIGHT_CURVE',
                        'VISION_SNAPSHOT','RFID_READ','TEMP_LOG')),
    url             VARCHAR(512),
    ref_event_id    BIGINT REFERENCES recognition_event(id),
    occurred_at     TIMESTAMP NOT NULL,
    note            VARCHAR(512)
);
CREATE INDEX idx_evidence_session ON session_evidence(session_id);

-- 销售订单
CREATE TABLE sale_order (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no        VARCHAR(64) NOT NULL UNIQUE,
    session_id      BIGINT NOT NULL REFERENCES door_session(id),
    cabinet_id      BIGINT NOT NULL REFERENCES cabinet(id),
    user_id         VARCHAR(64) NOT NULL,
    total_amount    NUMERIC(12,2) NOT NULL DEFAULT 0,
    -- PENDING/CONFIRMED 正常 / UNCERTAIN 证据不足待人工 / DISPUTED 投诉中
    -- REFUNDED 全额退 / PARTIALLY_REFUNDED 部分退 / CANCELLED 作废(卡货/误识别)
    status          VARCHAR(24) NOT NULL DEFAULT 'PENDING',
    uncertain       BOOLEAN NOT NULL DEFAULT FALSE,
    evidence_summary VARCHAR(1024),
    created_at      TIMESTAMP NOT NULL,
    settled_at      TIMESTAMP
);
CREATE INDEX idx_order_user ON sale_order(user_id);
CREATE INDEX idx_order_cabinet_time ON sale_order(cabinet_id, created_at);

-- 订单明细
CREATE TABLE order_item (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        BIGINT NOT NULL REFERENCES sale_order(id),
    sku             VARCHAR(64) NOT NULL,
    batch_id        BIGINT REFERENCES product_batch(id),
    channel_id      BIGINT REFERENCES channel(id),
    qty             INT NOT NULL,
    unit_price      NUMERIC(12,2) NOT NULL,
    subtotal        NUMERIC(12,2) NOT NULL,
    -- CHARGED 已计 / REVERSED_RETURN 拿起放回冲销 / JAM_EXCLUDED 卡货剔除 / REFUNDED 退款
    -- PENDING_REVIEW 证据不足待人工复核 / REJECTED 人工判定不计费
    status          VARCHAR(20) NOT NULL DEFAULT 'CHARGED'
                    CHECK (status IN ('CHARGED','REVERSED_RETURN','JAM_EXCLUDED','REFUNDED','PENDING_REVIEW','REJECTED'))
);
CREATE INDEX idx_order_item_order ON order_item(order_id);
CREATE INDEX idx_order_item_batch ON order_item(batch_id);

-- 退款(误扣款处理)
CREATE TABLE refund (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refund_no       VARCHAR(64) NOT NULL UNIQUE,
    order_id        BIGINT NOT NULL REFERENCES sale_order(id),
    amount          NUMERIC(12,2) NOT NULL,
    reason          VARCHAR(32) NOT NULL CHECK (reason IN (
                        'MISCHARGE','RETURN_NOT_RECOGNIZED','JAM','RECOGNITION_ERROR','COMPLAINT','OTHER')),
    detail          VARCHAR(512),
    status          VARCHAR(16) NOT NULL DEFAULT 'APPROVED'
                    CHECK (status IN ('APPROVED','REJECTED','DONE')),
    staff_id        BIGINT REFERENCES staff(id),
    created_at      TIMESTAMP NOT NULL,
    handled_at      TIMESTAMP
);

-- 温度记录
CREATE TABLE temperature_log (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cabinet_id      BIGINT NOT NULL REFERENCES cabinet(id),
    recorded_at     TIMESTAMP NOT NULL,
    temp_c          NUMERIC(5,2) NOT NULL,
    sensor          VARCHAR(32),
    status          VARCHAR(16) NOT NULL CHECK (status IN ('NORMAL','HIGH','LOW','RECOVERED'))
);
CREATE INDEX idx_temp_cabinet_time ON temperature_log(cabinet_id, recorded_at);

-- 温度告警(与库存隔离/报损联动)
CREATE TABLE temperature_alarm (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cabinet_id      BIGINT NOT NULL REFERENCES cabinet(id),
    started_at      TIMESTAMP NOT NULL,
    ended_at        TIMESTAMP,
    peak_c          NUMERIC(5,2),
    -- ACTICVE 持续中 / RECOVERED 恢复 / DISPOSED 已处置(隔离或报损)
    status          VARCHAR(16) NOT NULL DEFAULT 'ACTIVE'
                    CHECK (status IN ('ACTIVE','RECOVERED','DISPOSED')),
    action_taken    VARCHAR(32) CHECK (action_taken IN ('NONE','QUARANTINE','SCRAP')),
    staff_id        BIGINT REFERENCES staff(id),
    note            VARCHAR(512)
);

-- 卡货事件
CREATE TABLE jam_event (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cabinet_id      BIGINT NOT NULL REFERENCES cabinet(id),
    channel_id      BIGINT NOT NULL REFERENCES channel(id),
    batch_id        BIGINT REFERENCES product_batch(id),
    session_id      BIGINT REFERENCES door_session(id),
    qty             INT NOT NULL DEFAULT 1,
    occurred_at     TIMESTAMP NOT NULL,
    resolved_at     TIMESTAMP,
    -- OPEN / RESOLVED_RETURNED 取回重新上架 / SCRAPPED 报损 / IGNORED
    status          VARCHAR(20) NOT NULL DEFAULT 'OPEN'
                    CHECK (status IN ('OPEN','RESOLVED_RETURNED','SCRAPPED','IGNORED')),
    staff_id        BIGINT REFERENCES staff(id),
    note            VARCHAR(512)
);

-- 临期/异常下架任务
CREATE TABLE removal_record (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    removal_no      VARCHAR(64) NOT NULL UNIQUE,
    cabinet_id      BIGINT NOT NULL REFERENCES cabinet(id),
    batch_id        BIGINT NOT NULL REFERENCES product_batch(id),
    channel_id      BIGINT NOT NULL REFERENCES channel(id),
    qty             INT NOT NULL,
    -- NEAR_EXPIRY 临期 / EXPIRED 过期 / TEMP_ABNORMAL 温度异常 / MANUAL 人工 / DAMAGED 破损
    reason          VARCHAR(20) NOT NULL,
    -- PENDING 待下架(系统生成) / REMOVED 已下架 / RETURNED 复核合格回架 / SCRAPPED 已报损
    status          VARCHAR(20) NOT NULL DEFAULT 'PENDING'
                    CHECK (status IN ('PENDING','REMOVED','RETURNED','SCRAPPED')),
    staff_id        BIGINT REFERENCES staff(id),
    created_at      TIMESTAMP NOT NULL,
    handled_at      TIMESTAMP,
    note            VARCHAR(512)
);
CREATE INDEX idx_removal_status ON removal_record(status);
CREATE INDEX idx_removal_batch ON removal_record(batch_id);

-- 报损记录
CREATE TABLE scrap_record (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scrap_no        VARCHAR(64) NOT NULL UNIQUE,
    batch_id        BIGINT NOT NULL REFERENCES product_batch(id),
    cabinet_id      BIGINT REFERENCES cabinet(id),
    supplier_id     BIGINT NOT NULL REFERENCES supplier(id),
    qty             INT NOT NULL,
    cost_amount     NUMERIC(12,2) NOT NULL,
    -- EXPIRED 过期 / TEMP_SPOIL 温度变质 / JAM_DAMAGE 卡货损坏 / OTHER
    reason          VARCHAR(20) NOT NULL,
    settled         BOOLEAN NOT NULL DEFAULT FALSE,
    staff_id        BIGINT REFERENCES staff(id),
    created_at      TIMESTAMP NOT NULL,
    note            VARCHAR(512)
);
CREATE INDEX idx_scrap_batch ON scrap_record(batch_id);
CREATE INDEX idx_scrap_supplier ON scrap_record(supplier_id, settled);

-- 盘点任务
CREATE TABLE stocktake (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stocktake_no    VARCHAR(64) NOT NULL UNIQUE,
    cabinet_id      BIGINT NOT NULL REFERENCES cabinet(id),
    staff_id        BIGINT NOT NULL REFERENCES staff(id),
    started_at      TIMESTAMP NOT NULL,
    completed_at    TIMESTAMP,
    -- OPEN / CONFIRMED 无差异已确认 / ADJUSTED 有差异已调整
    status          VARCHAR(16) NOT NULL DEFAULT 'OPEN'
                    CHECK (status IN ('OPEN','CONFIRMED','ADJUSTED')),
    note            VARCHAR(512)
);

-- 盘点明细
CREATE TABLE stocktake_item (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stocktake_id   BIGINT NOT NULL REFERENCES stocktake(id),
    batch_id        BIGINT NOT NULL REFERENCES product_batch(id),
    channel_id      BIGINT NOT NULL REFERENCES channel(id),
    system_qty      INT NOT NULL,
    counted_qty     INT NOT NULL,
    diff_qty        INT NOT NULL,
    -- OK / JAM 卡货 / RECOGNITION_ERROR 识别偏差 / WRONG_CHANNEL 放错货道
    -- UNKNOWN_LOSS 原因不明 / MISCOUNT 初盘错误
    reason          VARCHAR(20) NOT NULL DEFAULT 'OK',
    handled         BOOLEAN NOT NULL DEFAULT FALSE,
    note            VARCHAR(512)
);
CREATE INDEX idx_stocktake_item_task ON stocktake_item(stocktake_id);

-- 供应商结算单
CREATE TABLE settlement (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    settlement_no   VARCHAR(64) NOT NULL UNIQUE,
    supplier_id     BIGINT NOT NULL REFERENCES supplier(id),
    period_start    DATE NOT NULL,
    period_end      DATE NOT NULL,
    -- DRAFT / CONFIRMED / PAID
    status          VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    sale_amount     NUMERIC(12,2) NOT NULL DEFAULT 0,
    scrap_amount    NUMERIC(12,2) NOT NULL DEFAULT 0,
    payable_amount  NUMERIC(12,2) NOT NULL DEFAULT 0,
    staff_id        BIGINT REFERENCES staff(id),
    created_at      TIMESTAMP NOT NULL,
    confirmed_at    TIMESTAMP,
    note            VARCHAR(512)
);

-- 结算明细(按批次)
CREATE TABLE settlement_item (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    settlement_id       BIGINT NOT NULL REFERENCES settlement(id),
    batch_id            BIGINT NOT NULL REFERENCES product_batch(id),
    sold_qty            INT NOT NULL DEFAULT 0,
    sale_cost_amount    NUMERIC(12,2) NOT NULL DEFAULT 0,
    scrapped_qty        INT NOT NULL DEFAULT 0,
    scrap_cost_amount   NUMERIC(12,2) NOT NULL DEFAULT 0,
    payable             NUMERIC(12,2) NOT NULL DEFAULT 0
);
CREATE INDEX idx_settlement_item_head ON settlement_item(settlement_id);

-- 用户投诉/售后工单
CREATE TABLE complaint (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    complaint_no    VARCHAR(64) NOT NULL UNIQUE,
    user_id         VARCHAR(64) NOT NULL,
    session_id      BIGINT REFERENCES door_session(id),
    order_id        BIGINT REFERENCES sale_order(id),
    reason          VARCHAR(256) NOT NULL,
    -- OPEN / INVESTIGATING / REFUNDED 已退款解决 / NO_FAULT 核实无责关闭 / CLOSED
    status          VARCHAR(20) NOT NULL DEFAULT 'OPEN',
    staff_id        BIGINT REFERENCES staff(id),
    created_at      TIMESTAMP NOT NULL,
    resolved_at     TIMESTAMP,
    resolution_note VARCHAR(1024)
);

-- 点位品类调整(运营按销量/损耗/临期率调整货道商品)
CREATE TABLE category_adjustment (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cabinet_id      BIGINT NOT NULL REFERENCES cabinet(id),
    channel_id      BIGINT NOT NULL REFERENCES channel(id),
    old_expected_sku VARCHAR(64),
    new_expected_sku VARCHAR(64),
    reason          VARCHAR(256),
    staff_id        BIGINT NOT NULL REFERENCES staff(id),
    applied         BOOLEAN NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMP NOT NULL,
    applied_at      TIMESTAMP
);

-- 运营告警(温度/临期/卡货/盘亏/错放货道/低库存)
CREATE TABLE operation_alert (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_type      VARCHAR(24) NOT NULL CHECK (alert_type IN (
                        'TEMP_ABNORMAL','NEAR_EXPIRY','EXPIRED','JAM',
                        'STOCK_MISMATCH','WRONG_CHANNEL','LOW_STOCK','UNCERTAIN_ORDER')),
    cabinet_id      BIGINT REFERENCES cabinet(id),
    ref_type        VARCHAR(32),
    ref_id          BIGINT,
    severity        VARCHAR(8) NOT NULL DEFAULT 'WARN' CHECK (severity IN ('INFO','WARN','CRITICAL')),
    message         VARCHAR(512),
    status          VARCHAR(8) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','ACK','CLOSED')),
    staff_id        BIGINT REFERENCES staff(id),
    created_at      TIMESTAMP NOT NULL,
    acknowledged_at TIMESTAMP
);
CREATE INDEX idx_alert_status ON operation_alert(status, alert_type);

-- 原始设备事件归档(Kafka 消费落库, 支持幂等与回放)
CREATE TABLE event_log (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id        VARCHAR(80) NOT NULL UNIQUE,
    event_type      VARCHAR(48) NOT NULL,
    cabinet_code    VARCHAR(64),
    occurred_at     TIMESTAMP,
    payload         TEXT,
    processed       BOOLEAN NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMP NOT NULL
);
CREATE INDEX idx_event_log_type ON event_log(event_type, processed);
